#include <bits/stdc++.h>
using namespace std;

int main()
{
    // 快速 I/O 优化，取消 cin 与 stdout 的同步，提高读入效率
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n;
    cin >> n;

    // a[1...n] 存储山丘高度
    // a[0] = 0, a[n+1] = 0 作为边界哨兵，避免处理首尾越界问题
    vector<int> a(n + 2, 0);
    for (int i = 1; i <= n; i++)
        cin >> a[i];

    const int INF = 1e9;
    int maxK = (n + 1) / 2; // n 个山丘最多能盖的房子数量 upper_bound

    // 滚动数组优化：只需保留上一步 i-1 (prev) 和当前步 i (cur) 的状态
    // prev[j][state]: 前 i-1 个山丘建造了 j 座房子，且山丘 i-1 处于 state 状态时的最小花费
    // state = 0: i-1 无房，i-2 无房
    // state = 1: i-1 无房，i-2 有房
    // state = 2: i-1 有房
    vector<array<int, 3>> prev(maxK + 1, {INF, INF, INF});
    vector<array<int, 3>> cur(maxK + 1, {INF, INF, INF});

    // 初始状态 (i = 1 时)：
    prev[0][0] = 0; // 山丘 1 不建房，建造 0 座房，代价为 0
    if (1 <= maxK)
        prev[1][2] = 0; // 山丘 1 建房，建造 1 座房，代价暂时记为 0（右邻居削减延迟计算）

    // 状态转移主循环
    for (int i = 2; i <= n; i++)
    {
        // 重置当前步 cur 的 DP 数组为极大值
        for (int j = 0; j <= maxK; j++)
            cur[j] = {INF, INF, INF};

        // 前 i 个山丘最多能盖的房子上限
        int maxJ = (i + 1) / 2;

        for (int j = 0; j <= maxJ; j++)
        {
            // -------------------------------------------------------------
            // 情况 A：从 prev[j][0] 转移 (i-1 无房，i-2 无房)
            // -------------------------------------------------------------
            if (prev[j][0] < INF)
            {
                // 1. 山丘 i 不建房：i-1 和 i 都无房 -> 转移至 cur[j][0]
                cur[j][0] = min(cur[j][0], prev[j][0]);

                // 2. 山丘 i 建房：转移至 cur[j+1][2]
                // 需要将山丘 i-1 削减到比 i 矮（原高 a[i-1] 没变过，因为 i-2 无房）
                if (j + 1 <= maxK)
                {
                    int cost = max(0, a[i - 1] - a[i] + 1);
                    cur[j + 1][2] = min(cur[j + 1][2], prev[j][0] + cost);
                }
            }
            // -------------------------------------------------------------
            // 情况 B：从 prev[j][1] 转移 (i-1 无房，i-2 有房)
            // -------------------------------------------------------------
            if (prev[j][1] < INF)
            {
                // 1. 山丘 i 不建房：i-1 夹在 i-2(有房) 和 i(无房) 中间
                // 之前 i-1 的高度可能还没被削减，需要结算使其严格低于 i-2 的代价
                int costL = max(0, a[i - 1] - a[i - 2] + 1);
                cur[j][0] = min(cur[j][0], prev[j][1] + costL);

                // 2. 山丘 i 建房：i-1 夹在两座房子 i-2 和 i 之间
                // 山丘 i-1 必须同时矮于两侧，即高度需降低至 min(a[i-2], a[i]) - 1
                if (j + 1 <= maxK)
                {
                    int costLR = max(0, a[i - 1] - min(a[i - 2], a[i]) + 1);
                    cur[j + 1][2] = min(cur[j + 1][2], prev[j][1] + costLR);
                }
            }
            // -------------------------------------------------------------
            // 情况 C：从 prev[j][2] 转移 (i-1 有房)
            // -------------------------------------------------------------
            if (prev[j][2] < INF)
            {
                // 因为相邻不能建房，山丘 i 必须不建房 -> 转移至 cur[j][1]
                // 此时山丘 i 作为 i-1(有房) 的右邻居，削减 i 的成本留到后面或结算阶段计算
                cur[j][1] = min(cur[j][1], prev[j][2]);
            }
        }
        // 交换指针/数组，准备下一轮循环（滚动数组关键步）
        swap(prev, cur);
    }

    // -------------------------------------------------------------
    // 最终结算：针对第 n 个山丘的三种不同末尾状态计算答案
    // -------------------------------------------------------------
    for (int k = 1; k <= maxK; k++)
    {
        // 1. n 无房，n-1 无房：成本已完全结算
        int ans = prev[k][0];

        // 2. n 无房，n-1 有房：山丘 n 作为右邻居尚未被削减，需补算削减成本
        if (prev[k][1] < INF)
            ans = min(ans, prev[k][1] + max(0, a[n] - a[n - 1] + 1));

        // 3. n 有房：其左邻居 n-1 在之前的转移中已被调整完毕
        ans = min(ans, prev[k][2]);

        cout << ans << (k == maxK ? '\n' : ' ');
    }
    return 0;
}
#include <bits/stdc++.h>
// #include <atcoder/all>

#ifdef YJL
#include <algo/debug.h> // 本地调试时使用的调试工具
#else
#define debug(...) 0 // 未定义 YJL 时，关闭调试输出
#define debugN(...) 0
#endif

    using namespace std;
using i64 = long long; // i64 是 long long 的别名，用来存储较大的异或值

void solve()
{
    int n, k;
    cin >> n >> k; // n：结点数量；k：关键点数量

    vector<i64> a(n); // a[i]：编号 i+1 的结点的权值
    vector<int> b(k); // b：关键点编号，之后会转换为从 0 开始的下标

    i64 s = 0; // 所有结点权值的异或和

    for (auto &x : a)
        cin >> x, s ^= x; // 读入权值，同时计算总异或和

    for (auto &x : b)
        cin >> x, x--; // 关键点编号减 1，转换成 0-based 下标

    sort(b.begin(), b.end()); // 按结点编号从小到大排列关键点

    // 如果最小的关键点编号是 0，说明结点 1 是关键点。
    // 因为 b 已排序，所以 b[0] == 0 就代表根结点 1 是关键点。
    if (b[0] == 0)
    {

        // 根结点 1 的子树就是整棵树。
        // 因此，所有结点权值的异或和必须为 0。
        if (s)
        {
            cout << "-1\n";
            return; // 总异或和不为 0，必定无解
        }

        b.erase(b.begin()); // 根结点的条件已经满足，移除这个关键点
        k--;                // 待处理的关键点数量减 1

        // 如果没有剩余关键点，任意一棵以 1 为根的树都合法。
        if (!k)
        {
            // 输出一条链：1-2-3-...-n
            for (int i = 1; i < n; ++i)
            {
                cout << i << " " << i + 1 << "\n";
            }
            return;
        }
    }

    vector<int> path; // 用来保存最终找到的结点添加顺序

    // f[mask]：状态 mask 下，已经完成的关键点数量/进度。
    // -1 表示该状态尚未被访问。
    vector<int> f(1 << n, -1);

    // pre[mask]：到达 mask 时所记录的前驱状态，
    // 用于在找到解后反向还原 path。
    vector<int> pre(1 << n, -1);

    // S[mask]：mask 对应结点集合的权值异或和。
    vector<i64> S(1 << n);

    int ft = -1; // 保存最终成功状态的位掩码
    f[0] = 0;    // 空集合初始状态：尚未完成任何关键点
    // S[0] 默认初始化为 0，因为空集合的异或和为 0。

    // 枚举所有子集状态。总状态数为 2^n。
    for (int i = 0; i < (1 << n); ++i)
    {

        // 最低位表示结点 1。
        // 本算法不把根结点 1 放进 mask，因此跳过最低位为 1 的状态。
        if (i & 1)
            continue;

        debug(bitset<5>(i)); // 调试输出：查看当前状态的二进制形式
        debug(f[i]);         // 调试输出：当前状态的关键点进度
        debug(S[i]);         // 调试输出：当前状态的异或和

        // 枚举所有非根结点：j 从 1 到 n-1。
        // j 是数组下标，对应实际结点编号 j+1。
        for (int j = 1; j < n; ++j)
        {

            // 检查结点 j+1 是否尚未加入当前集合 i。
            if (!(i >> j & 1))
            {

                // 把第 j 位设置为 1，相当于将结点 j+1 加入集合。
                // 因为这一位原来是 0，所以异或 1<<j 等价于置位。
                int t = i ^ (1 << j);

                // 新集合的异或和 = 原集合异或和 XOR 新加入结点的权值。
                S[t] = S[i] ^ a[j];

                // 普通转移：加入一个结点，但不增加关键点完成数量。
                // 如果新状态尚未访问，或者当前进度更好，就更新它。
                if (f[t] < f[i])
                {
                    f[t] = f[i];
                    pre[t] = i; // 记录到达 t 的前驱是 i
                }

                // 尝试通过当前加入的结点完成下一个关键点。
                //
                // 条件 1：S[t] == 0
                //         当前集合的异或和为 0。
                //
                // 条件 2：f[i] < k
                //         仍有关键点需要完成，避免访问 b[k] 越界。
                //
                // 条件 3：b[f[i]] == j
                //         当前加入的结点正好是下一个关键点。
                //
                // 条件 4：f[t] <= f[i]
                //         不覆盖一个已经拥有更高关键点进度的状态。
                if (S[t] == 0 &&
                    f[i] < k &&
                    b[f[i]] == j &&
                    f[t] <= f[i])
                {

                    // 成功完成一个关键点，进度加 1。
                    f[t] = f[i] + 1;
                    pre[t] = i; // 记录这次关键点完成转移的前驱状态

                    // 所有关键点都已完成，找到目标状态。
                    if (f[t] >= k)
                    {
                        int p = t;

                        // 从目标状态开始，沿 pre 指针逆向还原路径。
                        // 每次状态转移只加入一个结点。
                        while (p > 0)
                        {
                            debug(p, pre[p]);

                            // p XOR pre[p] 只有一位为 1，
                            // 这一位就是本次加入结点的下标。
                            // __lg(x) 返回 x 的最高位下标。
                            path.push_back(__lg(p ^ pre[p]));

                            // 回到上一个状态。
                            p = pre[p];
                        }

                        ft = t; // 记录成功终止状态

                        break; // 退出当前的 j 循环
                    }
                }
            }
        }

        // 如果已经找到完整路径，就不再继续枚举状态。
        if (!path.empty())
            break;
    }

    // 没有找到能够完成所有关键点的路径，输出 -1。
    if (path.empty())
    {
        cout << "-1\n";
        return;
    }

    // 回溯时得到的是反向顺序，需要翻转成正向添加顺序。
    reverse(path.begin(), path.end());

    debug(path);
    debug(bitset<5>(ft)); // 调试输出：最终状态的位掩码

    int i = 0; // b[i] 表示当前等待处理的关键点

    // 根据 path 中的结点顺序构造树。
    for (auto &x : path)
    {

        // path 和 b 都使用从 0 开始的下标。
        // 如果当前结点就是下一个关键点：
        if (x == b[i])
        {

            // 将关键点连接到根结点 1。
            // 下标 b[i] 转换回实际结点编号，需要 +1。
            cout << b[i] + 1 << " " << 1 << "\n";

            // 当前关键点已经处理完，切换到下一个关键点。
            i++;
        }
        else
        {

            // 当前结点不是下一个关键点，
            // 就将它连接到当前等待处理的关键点下方。
            cout << x + 1 << " " << b[i] + 1 << "\n";
        }
    }

    // 处理没有进入最终状态 ft 的结点。
    // 这些结点不在 path 中，直接连接到根结点 1。
    for (int j = 1; j < n; ++j)
    {

        // 检查结点 j+1 是否不属于最终状态 ft。
        if (!(ft >> j & 1))
        {
            cout << 1 << " " << j + 1 << "\n";
        }
    }
}

int main()
{
    cin.tie(nullptr)->sync_with_stdio(false); // 加速输入输出

#ifdef YJLFILE
    freopen("1.in", "r", stdin); // 本地调试时从 1.in 读取输入
#endif

    int t = 1;
    // cin >> t; // 当前题目只处理一组输入，因此没有读取测试组数

    while (t--)
    {
        solve();
    }

    return 0;
}
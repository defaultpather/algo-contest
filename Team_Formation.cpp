#include<bits/stdc++.h>
using namespace std;

#define int long long

const int linf=1e18;
const int B=1<<24;

signed main(){
    ios::sync_with_stdio(false);
    cin.tie(0);

    int n;
    cin>>n;
    int N=3*n;
    vector<vector<int>>a(N,vector<int>(N));
    for(int i=0;i<N;i++){
        for(int j=0;j<N;j++){
            cin>>a[i][j];
        }
    }
    // int B=1<<N;
    vector<int>dp(B,-linf);
    dp[0]=0;
    int i=linf;
    for(int mask=0;mask<B;mask++){
        if(dp[mask]==-linf)continue;
        //第一个未被选择的
        i=linf;
        for(int c=0;c<N;c++){
            if((mask>>c&1)==0){
                i=c;
                break;
            }
        }
        if(i==linf)continue;
        for(int j=i+1;j<N;j++){
            if((mask>>j&1))continue;
            for(int k=j+1;k<N;k++){
                if((mask>>k&1))continue;
                int sum=a[i][j]+a[i][k]+a[j][k];
                int path=mask|(1ll<<i)|(1ll<<j)|(1ll<<k);
                dp[path]=max(dp[path],dp[mask]+sum);
            }
        }
    }
    // for(int i=0;i<B;i++){
    //     cout<<dp[i]<<" ";
    // }
    // cout<<endl;
    cout<<dp[(1<<N)-1]<<endl;
}
